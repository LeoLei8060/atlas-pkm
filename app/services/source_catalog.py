def list_catalog() -> list[dict[str, Any]]:
    return [
        {
            key: value
            for key, value in item.items()
            if key in {"id", "category", "name", "adapter", "url", "description", "priority"}
        }
        for item in CATALOG
    ]


def catalog_entry(entry_id: str) -> dict[str, Any] | None:
    return next((item for item in CATALOG if item["id"] == entry_id), None)


def add_catalog_sources(ids: list[str]) -> list[dict[str, Any]]:
    added: list[dict[str, Any]] = []
    for entry_id in dict.fromkeys(ids):
        entry = catalog_entry(entry_id)
        if entry is None:
            continue
        added.append(
            add_source(
                url=entry["url"],
                name=entry["name"],
                source_group="other",
                adapter=entry["adapter"],
                config=entry["config"],
            )
        )
    return added
